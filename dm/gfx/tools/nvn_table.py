#!/usr/bin/env python3
# 从名字表重建宿主侧的 NVN 跳板表与计数表，并维护「无原型」名单。
# gen_protos.py 需要 Nintendo 的 nvn.h（仓库外、Mac 侧），本脚本不需要：跳板与计数表只依赖名字表，
# 所以名字表扩了（TotK 新增接口）之后可以在任何机器上重建。
# 产出：
#   nvn_thunks.S  每个名字一个计数跳板 + 跳板指针表 + 名字指针表 + 名字字符串
#   nvn_count.h   NVN_NFUNC
#   nvn_protos.h  只维护末尾「头文件里没有原型的名字（新版接口）」名单（其余原型不动）
# 仓内这几张生成表是 CRLF 行尾（gen_protos.py 在 Windows 上以文本模式写出），本脚本保持一致。
# 用法：nvn_table.py [--check] [--names <名字表>] [--dir <dm/gfx/nvn 目录>]
#   --check 只比对，不写文件（有差异时非零退出）
# Rebuild the host-side NVN trampoline/count tables from the name table and keep the
# "no prototype" list in nvn_protos.h in sync. gen_protos.py needs Nintendo's nvn.h (outside
# this repo, on the Mac side); this script does not, because the trampolines depend only on the names.
# Usage: nvn_table.py [--check] [--names <name table>] [--dir <dm/gfx/nvn directory>]
import argparse, pathlib, re, sys

ap = argparse.ArgumentParser()
ap.add_argument('--check', action='store_true')
ap.add_argument('--names', default=None)
ap.add_argument('--dir', default=None)
ap.add_argument('--merge', default=None, help='把另一款游戏的 NVN 名字表并进 names.txt（缺的追加到末尾）')
a = ap.parse_args()

EOL = '\r\n'   # 这几张生成表在仓内是 CRLF | these generated tables use CRLF in this repo

root = pathlib.Path(__file__).resolve().parents[2]
nvn_dir = pathlib.Path(a.dir) if a.dir else root / 'gfx' / 'nvn'
names_path = pathlib.Path(a.names) if a.names else nvn_dir / 'names.txt'

def raw(path):
    # 统一成 LF 比较（read_text 会做通用换行转换），写回时再按 CRLF 落盘。
    # Normalize to LF for comparison; files are written back with CRLF.
    return pathlib.Path(path).read_text(encoding='utf-8')

def write(path, text):
    with open(path, 'w', encoding='utf-8', newline='\r\n') as f: f.write(text)

def read_names(path):
    out = []
    for line in raw(path).splitlines():
        s = line.strip()
        if s and not s.startswith('#'): out.append(s)
    return out

names = read_names(names_path)

if a.merge:
    # 并表：D2R 的名字顺序不动（槽索引不变，D2R 行为逐字节不变），TotK 独有的名字追加到末尾。
    # Merge: keep the D2R order (slot indices unchanged, D2R behaviour byte-identical) and append the names only TotK has.
    game = read_names(a.merge)
    have = set(names)
    added = [n for n in game if n not in have]
    if added:
        if a.check:
            print(f'x names.txt 缺 {len(added)} 个名字：{", ".join(added)}')
        else:
            with open(names_path, 'a', encoding='utf-8', newline='') as f:
                for n in added: f.write(n + '\r\n')
            print(f'- names.txt 追加 {len(added)} 个名字 | appended {len(added)} names to names.txt')
        names += added
    else:
        print('names.txt 已覆盖该游戏的名字表 | names.txt already covers this game')

S = ['// 由 dm/gfx/tools/gen_protos.py 生成，勿手改。',
     '// 计数用 LSE 原子 stadd（ARMv8.1；Apple A12 / M1 起全部支持）：下一行让本文件不依赖编译器的 -mcpu 基线。',
     "// Generated by dm/gfx/tools/gen_protos.py, do not edit by hand.",
     "// Counting uses the LSE atomic stadd (ARMv8.1; supported by everything from Apple A12 / M1 on): the next line makes this file independent of the compiler's -mcpu baseline.",
     '    .arch_extension lse', '    .text', '    .p2align 2']
for i, n in enumerate(names):
    S += [f'    .globl _nvnth_{i}', f'_nvnth_{i}:',
          '    adrp x16, _nvn_slot@PAGE', '    add x16, x16, _nvn_slot@PAGEOFF',
          f'    mov x17, #{i * 16}', '    add x16, x16, x17',
          '    mov x17, #1', '    stadd x17, [x16]', '    ldr x17, [x16, #8]', '    br x17']
S += ['    .data', '    .p2align 3', '    .globl _nvn_thunk', '_nvn_thunk:'] + [f'    .quad _nvnth_{i}' for i in range(len(names))]
S += ['    .globl _nvn_names', '_nvn_names:'] + [f'    .quad Ln{i}' for i in range(len(names))]
S += ['    .cstring'] + [f'Ln{i}: .asciz "{n}"' for i, n in enumerate(names)]
thunks = '\n'.join(S) + '\n'
count = '// 由 gen_protos.py 生成\n// Generated by gen_protos.py\n#pragma once\n#define NVN_NFUNC %d\n' % len(names)

# nvn_protos.h：只维护末尾的「无原型」名单
pp = nvn_dir / 'nvn_protos.h'
protos = raw(pp)
have = set(re.findall(r'typedef\s+.*\(\*NVNT_(\w+)\)\(', protos))
missing = [n for n in names if n not in have]
MARK = '// 头文件里没有原型的名字（新版接口）：只能接记名桩'
head, sep, tail = protos.partition(MARK)
if not sep:
    head, sep = protos.rstrip('\n'), '\n' + MARK
    tail = '\n'
else:
    tail = tail.lstrip('\n')
# 只替换中文名单本身，名单之后的内容（英文镜像名单等）原样保留。
# Replace only the Chinese list; whatever follows it (e.g. the English mirror) is kept as is.
tl = tail.split('\n')
k = 0
while k < len(tl) and tl[k].startswith('//   '): k += 1
block = MARK + '\n' + ''.join(f'//   {n}\n' for n in missing) + '\n'.join(tl[k:])
new_protos = head + block

def report(path, want):
    if raw(path) == want: return True
    if a.check:
        print(f'x {path.name} 与名字表不一致 | {path.name} does not match the name table')
        return False
    write(path, want)
    print(f'- 重写 {path.name} | rewrote {path.name}')
    return True

ok = True
ok &= report(nvn_dir / 'nvn_thunks.S', thunks)
ok &= report(nvn_dir / 'nvn_count.h', count)
ok &= report(pp, new_protos)
print(f'名字 {len(names)}，无原型 {len(missing)}')
sys.exit(0 if ok else 1)
